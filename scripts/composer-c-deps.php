<?php

// Generates vendor/c-deps.mk from the installed composer packages, so the
// Makefile can pick up their include paths and sources.
//
// A package can describe its layout in its composer.json:
//
//   "extra": {
//       "c": {
//           "include": ["src"],
//           "sources": ["src/*.c"]
//       }
//   }
//
// Paths are relative to the package root, and sources may be glob patterns.
// Packages without this section default to the values above.

$vendor_dir = dirname(__DIR__) . '/vendor';
$installed = json_decode(file_get_contents($vendor_dir . '/composer/installed.json'), true);
$packages = $installed['packages'] ?? $installed;

$lines = ["# Generated by scripts/composer-c-deps.php. Do not edit."];

foreach ($packages as $package) {
    $config = ($package['extra']['c'] ?? []) + [
        'include' => ['src'],
        'sources' => ['src/*.c'],
    ];
    $package_dir = 'vendor/' . substr($package['install-path'], strlen('../'));

    $lines[] = '';
    $lines[] = '# ' . $package['name'];
    foreach ($config['include'] as $include) {
        $lines[] = "INCLUDES += -I./$package_dir/$include";
    }
    foreach ($config['sources'] as $pattern) {
        $matches = glob(dirname(__DIR__) . "/$package_dir/$pattern");
        if (!$matches) {
            fwrite(STDERR, "{$package['name']}: no sources match \"$pattern\"\n");
            exit(1);
        }
        foreach ($matches as $source) {
            $lines[] = 'SRCS += ./' . substr($source, strlen(dirname(__DIR__)) + 1);
        }
    }
}

file_put_contents($vendor_dir . '/c-deps.mk', implode("\n", $lines) . "\n");
